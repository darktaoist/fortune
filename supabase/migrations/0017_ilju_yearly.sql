-- ============================================================================
-- 타오운세 2.0 — 0017 일주(日柱)별 연도 참고 해석 (ilju_yearly)
-- 유료 신년운세·평생사주 프롬프트에 "참고 해석"으로 넣는 데이터. 화면에 직접 나가지 않는다.
--
-- 키: (year, ilju, lang). ilju = 일주 한자 간지 2글자('甲子'~'癸亥', 60개).
-- lang은 앱 로케일 코드(ko/en/ja/zh). relation = 그해 세운(예: 丁未)과 일주의
-- 생극·합충을 코드로 계산한 값(생성 입력과 같은 것) — 모델이 계산하지 않는다.
--
-- 유료 리포트의 재료라 공개 읽기 정책을 두지 않는다(0016과 같은 방식). RLS만 켜 두면
-- anon/authenticated는 0행, 서버(service role)만 읽는다.
-- ============================================================================
begin;

create table public.ilju_yearly (
  id bigint generated by default as identity primary key,
  year smallint not null,
  ilju char(2) not null,
  lang varchar(5) not null check (lang in ('ko', 'en', 'ja', 'zh')),
  relation jsonb not null,
  nature text not null,
  year_relation text not null,
  wealth text not null,
  career text not null,
  love text not null,
  health text not null,
  caution text not null,
  status varchar(10) not null default 'draft' check (status in ('draft', 'published')),
  model varchar(40),
  prompt_ver varchar(20),
  created_at timestamptz not null default now(),
  unique (year, ilju, lang)
);

alter table public.ilju_yearly enable row level security;

commit;
