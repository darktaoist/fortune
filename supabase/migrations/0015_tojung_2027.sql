-- ============================================================================
-- 타오운세 2.0 — 0015 2027 토정비결 콘텐츠 테이블 (tojung_yearly / tojung_monthly)
-- 기존 public.tojung(2026판, num 000~071)은 건드리지 않는 별도 테이블.
--
-- 키 체계: scheme='legacy72' + gwae_code = tojung.post.ts의 tojungNumber() 계산값
-- 그대로('001'~'072'). 기존 테이블의 1칸 어긋남(테이블 000~071)은 옮기지 않는다.
-- 성별이 키에 들어간다(001~036 남, 037~072 여). 나중에 전통 144괘(111~863)를
-- 쓰게 되면 scheme만 달리해 같은 테이블에 공존시킨다.
--
-- lang은 앱 로케일 코드(ko/en/ja/zh) — tojung.nation(k/e/j/c)과 다르다.
-- 읽기 정책은 published만. draft는 service role(RLS 우회)로만 보인다.
-- ============================================================================
begin;

create table public.tojung_yearly (
  id bigint generated by default as identity primary key,
  year smallint not null,
  scheme varchar(10) not null default 'legacy72',
  gwae_code char(3) not null,
  lang varchar(5) not null,
  grade smallint check (grade between 1 and 5),
  headline text not null,
  summary text not null,
  total text not null,
  wealth text, career text, love text, health text, family text, caution text,
  good_months smallint[],
  bad_months smallint[],
  lucky jsonb,
  status varchar(10) not null default 'draft' check (status in ('draft', 'published')),
  model varchar(40),
  prompt_ver varchar(20),
  created_at timestamptz not null default now(),
  constraint tojung_yearly_legacy72_code check (scheme <> 'legacy72' or (gwae_code ~ '^[0-9]{3}$' and gwae_code between '001' and '072')),
  unique (year, scheme, gwae_code, lang)
);

create table public.tojung_monthly (
  id bigint generated by default as identity primary key,
  year smallint not null,
  scheme varchar(10) not null default 'legacy72',
  gwae_code char(3) not null,
  lang varchar(5) not null,
  month smallint not null check (month between 1 and 12),
  grade smallint check (grade between 1 and 5),
  summary text not null,
  body text not null,
  wealth text, career text, love text, health text, advice text,
  status varchar(10) not null default 'draft' check (status in ('draft', 'published')),
  created_at timestamptz not null default now(),
  constraint tojung_monthly_legacy72_code check (scheme <> 'legacy72' or (gwae_code ~ '^[0-9]{3}$' and gwae_code between '001' and '072')),
  unique (year, scheme, gwae_code, lang, month)
);

alter table public.tojung_yearly  enable row level security;
alter table public.tojung_monthly enable row level security;
create policy yearly_read  on public.tojung_yearly  for select to public using (status = 'published');
create policy monthly_read on public.tojung_monthly for select to public using (status = 'published');

commit;
