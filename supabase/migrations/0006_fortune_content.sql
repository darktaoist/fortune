-- 띠별 오늘의 운세 (daily)
create table if not exists public.daily_horoscope (
  id          uuid default gen_random_uuid() primary key,
  target_date date not null,
  zodiac_ko   varchar(10) not null,
  birth_years text not null,
  "content"   text not null,
  created_at  timestamptz default now(),
  lang        varchar(5) default 'ko' not null,
  constraint daily_horoscope_unique unique (target_date, zodiac_ko, lang)
);
create index if not exists idx_horoscope_date on public.daily_horoscope using btree (target_date);

-- 오늘의 운세 content pool (no PK in 1.0 — mirrored)
create table if not exists public.today (
