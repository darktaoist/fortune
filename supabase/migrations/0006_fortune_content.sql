-- RLS: public read on all content pools
do $$
declare t text;
begin
  foreach t in array array['daily_horoscope','today','today_date_unse','month_unse','tojung','lifeall','lotto']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t||'_select_public', t);
    execute format('create policy %I on public.%I for select using (true)', t||'_select_public', t);
  end loop;
end $$;
